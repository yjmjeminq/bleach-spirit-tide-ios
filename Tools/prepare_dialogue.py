SCENES = []


def line(speaker, text):
    return {"speaker": speaker, "text": text.replace("\u200b", "")}


def add(id, act, stage, kind, title, place, pairs, responses=None):
    data = {"id": id, "act": act, "stage": stage, "kind": kind, "title": title, "place": place,
            "lines": [line(*pair) for pair in pairs], "responses": responses or []}
    if responses:
        assert len(responses) == 6
        data["lines"].append(line("$lead", "$response"))
    SCENES.append(data)
    return data


