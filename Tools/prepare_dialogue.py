def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def write(path, data):
    content=json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    if not path.is_file() or path.read_text(encoding="utf-8")!=content:
        path.write_text(content, encoding="utf-8")


