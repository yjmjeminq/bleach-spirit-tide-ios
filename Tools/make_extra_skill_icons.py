CELL = 128
SCALE = 2.56


def point(pair):
    return tuple(round(int(axis) * SCALE) for axis in pair.split(","))


def make_icon(hue, paths):
    size = CELL * 2
    image = Image.new("RGB", (size, size))
    pixels = image.load()
    for y in range(size):
        for x in range(size):
            r = ((x - 128) ** 2 + (y - 123) ** 2) ** .5 / 170
            light = max(0, 1 - r)
            pixels[x, y] = tuple(round(9 + channel * (.04 + .19 * light)) for channel in hue)

    frame = ImageDraw.Draw(image)
    frame.rounded_rectangle((5, 5, 250, 250), 24, outline=tuple(v // 2 for v in hue), width=4)
    frame.rounded_rectangle((14, 14, 241, 241), 19, outline=tuple(v // 5 for v in hue), width=2)
    for degrees in range(4):
        x = (22, 224, 22, 224)[degrees]
        y = (22, 22, 224, 224)[degrees]
        frame.ellipse((x, y, x + 9, y + 9), fill=tuple(v * 2 // 3 for v in hue))

    points = [[point(p) for p in path.split()] for path in paths]
    mask = Image.new("L", image.size)
    for line in points:
        ImageDraw.Draw(mask).line(line, fill=170, width=16, joint="curve")
    image.paste(hue, mask=mask.filter(ImageFilter.GaussianBlur(9)))
    glow = tuple(round(channel * .72 + 255 * .28) for channel in hue)
    for line in points:
        draw = ImageDraw.Draw(image)
        draw.line(line, fill=hue, width=11, joint="curve")
        draw.line(line, fill=glow, width=6, joint="curve")
    return image.resize((CELL, CELL), Image.Resampling.LANCZOS)


