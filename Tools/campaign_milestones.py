def add_milestones(campaign, mains, scene):
    for act, points in enumerate(CHECKPOINTS, 1):
        for order, (stage, address, title, goal, grant, lines) in enumerate(points):
            dungeon = campaign["stages"][(act - 1) * 6 + stage - 1]
            rooms = dungeon["rooms"]
            extended = [i for i, room in enumerate(rooms) if room.get("extension")]
            index = 0 if address == -1 else extended[address]
            assert index < len(rooms) - 1
            bit = (act - 1) * 5 + order
            scene_id = scene(f"main_a{act}_evidence{order + 1}", act, stage, "main_checkpoint", title,
                             rooms[index]["title"], lines, quest_step=bit)
            mains[act - 1].setdefault("milestones", []).append({
                "bit": bit, "stage": stage, "room": index, "title": title, "goal": goal,
                "x": (5.65, 6.35, 5.25, 6.6, 5.6)[order], "y": (.62, -.3, .8, -.72, .45)[order],
                "grant": grant, "scene": scene_id,
            })
