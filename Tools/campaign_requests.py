def add_requests(campaign, add):
    for act, cases in enumerate(REQUESTS, 1):
        for stage, (giver, title, offer, response, actions, after, memory) in enumerate(cases, 1):
            npc = GIVERS[giver]
            rooms = campaign["stages"][(act - 1) * 6 + stage - 1]["rooms"]
            extended = [i for i, room in enumerate(rooms) if room.get("extension")]
            steps = []
            for kind, offset, marker, goal, pairs in actions:
                index = extended[offset]
                room = rooms[index]
                assert kind != "site" or index < len(rooms) - 1
                assert kind != "ward" or room["ward"]
                assert kind != "signal" or room.get("signal_wave")
                steps.append({"kind": kind, "stage": stage, "room": index, "title": marker, "goal": goal,
                              "npc": "", "x": 3.15, "y": -1.05, "lines": pairs})
            closing = [(npc, after), (response[0], CLOSINGS[act - 1][stage - 1])]
            q = add(act, stage + 3, giver, title, offer, [(npc, offer), response], steps, closing, after, memory, unlock=stage)
            q["active_line"] = offer
            q["ready_line"] = READY[giver].format(title)
            q["choice_notes"] = [after]
            q["choice_keepsakes"] = [memory]
